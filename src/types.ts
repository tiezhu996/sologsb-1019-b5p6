export type CoderId = 'A' | 'B';

export interface DefinitionVersion {
  id: string;
  version: number;
  text: string;
  createdAt: string;
  note?: string;
}

export interface Theme {
  id: string;
  name: string;
  parentId: string | null;
  color: string;
  definition: string;
  memo: string;
  examples: string[];
  currentVersionId: string;
  definitionVersions: DefinitionVersion[];
}

export type AssignmentStatus = 'current' | 'pending' | 'legacy';

export interface Assignment {
  themeId: string;
  versionId: string;
  status: AssignmentStatus;
}

export interface Segment {
  id: string;
  transcriptId: string;
  order: number;
  speaker: string;
  time: string;
  text: string;
  assignments: Record<CoderId, Assignment[]>;
  note: string;
}

export interface Transcript {
  id: string;
  title: string;
  participant: string;
  importedAt: string;
  sourceName: string;
}

export interface CodingState {
  revision: number;
  updatedAt: string;
  activeTranscriptId: string;
  activeSegmentId: string;
  activeThemeId: string;
  coderA: string;
  coderB: string;
  transcripts: Transcript[];
  segments: Segment[];
  themes: Theme[];
  audit: Array<{ id: string; at: string; action: string; detail: string }>;
}

export interface PersistedEnvelope {
  revision: number;
  updatedAt: string;
  writerId: string;
  state: CodingState;
}
